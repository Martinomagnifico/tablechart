// vite.config.ts
import { defineConfig, build } from 'vite';
import { resolve } from 'path';
import { dts } from 'rolldown-plugin-dts';

// Browsers that know light-dark(), so the build leaves it as it is; the stylesheet already needs oklch(from …).
const CSS_TARGET = ['chrome123', 'edge123', 'firefox120', 'safari17.5'];

const iifeBuild = () => ({
  name: 'iife-build',
  closeBundle: async () => {
    await build({
      configFile: false,
      build: {
        lib: {
          entry: resolve(import.meta.dirname, 'src/js/index.iife.ts'),
          name: 'Tablechart',
          formats: ['iife'],
          fileName: () => 'tablechart.js'
        },
        emptyOutDir: false,
        sourcemap: false,
        minify: 'terser',
        // This build writes tablechart.css as well, so it needs the same browsers.
        cssTarget: CSS_TARGET,
        terserOptions: {
          // Smaller bundle.
          mangle: { properties: { regex: /^_/ } },
          compress: { passes: 3 }
        },
        target: 'es2020'
      }
    });
  }
});



export default defineConfig({
  // rolldown-plugin-dts: keep generated declarations away from Oxc (and JS, as Vite does by default)
  oxc: { exclude: [/\.js$/, /\.d\.[cm]?ts$/] },
  plugins: [
    // Bundled types per entry, generated by tsc and bundled by rolldown
    dts({ tsconfig: 'tsconfig.json' }),
    iifeBuild()
  ],
  build: {
    // One ES module per entry: dist/tablechart.mjs for init() and create(), and
    // dist/tablechart-core.mjs for the building blocks under them. The stylesheet
    // is dist/tablechart.css.
    lib: {
      entry: {
        tablechart: resolve(import.meta.dirname, 'src/js/index.ts'),
        'tablechart-core': resolve(import.meta.dirname, 'src/js/blocks.ts'),
      },
      formats: ['es'],
      fileName: (_format, name) => `${name}.mjs`,
      cssFileName: 'tablechart',
    },
    rollupOptions: {
      // Both entries use the same code, so it is in one shared file that they
      // both import: dist/tablechart-shared.mjs.
      output: {
        chunkFileNames: chunk => chunk.name.endsWith('.d') ? 'tablechart-shared.d.mts' : 'tablechart-shared.mjs',
      },
    },
    sourcemap: false,
    minify: 'oxc',
    target: 'es2020',
    cssTarget: CSS_TARGET
  },
  server: {
    host: true,
    open: "index.html",
}
});
// vite.config.ts
import { defineConfig, build } from 'vite';
import { resolve } from 'path';
import { dts } from 'rolldown-plugin-dts';

// Browsers that know light-dark(), so the build leaves it as it is; the stylesheet already needs oklch(from …).
const MAIN_ENTRY = resolve(import.meta.dirname, 'src/js/index.ts');
const CORE_ENTRY = resolve(import.meta.dirname, 'src/js/blocks.ts');
// The modules the main entries use, worked out once per build from their imports.
let mainCode = null;

const CSS_TARGET = ['chrome123', 'edge123', 'firefox120', 'safari17.5'];

// One script for a <script> tag. The additional types take the helpers of the core from `Tablechart.kit`, so they hold no copy.
const iife = (entry, fileName, rollupOptions = {}) =>
  build({
    configFile: false,
    build: {
      lib: {
        entry: resolve(import.meta.dirname, entry),
        name: 'Tablechart',
        formats: ['iife'],
        fileName: () => fileName
      },
      emptyOutDir: false,
      sourcemap: false,
      minify: 'terser',
      // This build writes tablechart.css as well, so it needs the same browsers.
      cssTarget: CSS_TARGET,
      terserOptions: {
        // Smaller bundle.
        mangle: { properties: { regex: /^_/ } },
        compress: { passes: 3 }
      },
      target: 'es2020',
      rollupOptions
    }
  });

const iifeBuild = () => ({
  name: 'iife-build',
  closeBundle: async () => {
    await iife('src/js/index.iife.ts', 'tablechart.js');
    const kit = (id) => /[/\\]kit(\.ts)?$/.test(id);
    await iife('src/js/additional-types.iife.ts', 'tablechart-additional-types.js', {
      external: kit,
      output: { globals: (id) => (kit(id) ? 'Tablechart.kit' : id) }
    });
    await iife('src/js/summary.iife.ts', 'tablechart-summary.js', {
      external: kit,
      output: { globals: (id) => (kit(id) ? 'Tablechart.kit' : id) }
    });
  }
});



export default defineConfig({
  // rolldown-plugin-dts: keep generated declarations away from Oxc (and JS, as Vite does by default)
  oxc: { exclude: [/\.js$/, /\.d\.[cm]?ts$/] },
  plugins: [
    // Bundled types per entry, generated by tsc and bundled by rolldown
    dts({ tsconfig: 'tsconfig.json' }),
    iifeBuild()
  ],
  build: {
    // One ES module per entry: dist/tablechart.mjs for init() and create(),
    // dist/tablechart-core.mjs for the building blocks under them, and
    // dist/tablechart-additional-types.mjs for chart types not every page needs. The stylesheet
    // is dist/tablechart.css.
    lib: {
      entry: {
        tablechart: MAIN_ENTRY,
        'tablechart-core': CORE_ENTRY,
        'tablechart-additional-types': resolve(import.meta.dirname, 'src/js/additional-types.ts'),
        'tablechart-summary': resolve(import.meta.dirname, 'src/js/summary.ts'),
      },
      formats: ['es'],
      fileName: (_format, name) => `${name}.mjs`,
      cssFileName: 'tablechart',
    },
    rollupOptions: {
      // All code of the two main entries is in one shared file, also the part the additional types use:
      // dist/tablechart-shared.mjs. Code that only an additional type needs stays in its own entry.
      output: {
        manualChunks: (id, { getModuleInfo }) => {
          if (!mainCode) {
            mainCode = new Set();
            const walk = (one) => {
              if (mainCode.has(one)) return;
              mainCode.add(one);
              for (const next of getModuleInfo(one)?.importedIds ?? []) walk(next);
            };
            walk(MAIN_ENTRY);
            walk(CORE_ENTRY);
          }
          // The types of all entries share one file too.
          if (/\.d\.[mc]?ts$/.test(id)) return /[/\\](index|blocks|additional-types|summary)\.d\.[mc]?ts$/.test(id) ? undefined : 'shared.d';
          if (/\.[mc]?[jt]s$/.test(id) && id !== MAIN_ENTRY && id !== CORE_ENTRY && mainCode.has(id)) return 'shared';
        },
        chunkFileNames: chunk => chunk.name.endsWith('.d') ? 'tablechart-shared.d.mts' : 'tablechart-shared.mjs',
      },
    },
    sourcemap: false,
    minify: 'oxc',
    target: 'es2020',
    cssTarget: CSS_TARGET
  },
  server: {
    host: true,
    open: "index.html",
}
});